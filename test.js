const K = require('./interpreter.js');

let pass = 0, fail = 0;

function ok(name, src, expectOutput, opts) {
  try {
    const r = K.createRunner(src, opts || {}).runAll();
    if (r.error) {
      console.log(`✗ ${name}\n    运行时错误: ${r.error.message} (第${r.error.line}行)`);
      fail++; return;
    }
    const got = r.snapshots.length ? r.snapshots[r.snapshots.length - 1].output : [];
    const g = JSON.stringify(got), e = JSON.stringify(expectOutput);
    if (g === e) { console.log(`✓ ${name}`); pass++; }
    else { console.log(`✗ ${name}\n    期望 ${e}\n    实际 ${g}`); fail++; }
  } catch (e) {
    console.log(`✗ ${name}\n    ${e.name === 'LangError' ? e.message + ' (第' + e.line + '行)' : e.stack}`);
    fail++;
  }
}

function bad(name, src, keyword) {
  try {
    const r = K.createRunner(src).runAll();
    if (!r.error) { console.log(`✗ ${name} —— 本该报错却跑通了`); fail++; return; }
    const m = r.error.message;
    if (keyword && !m.includes(keyword)) { console.log(`✗ ${name}\n    报错不含「${keyword}」: ${m}`); fail++; return; }
    console.log(`✓ ${name}  →  ${m}`);
    pass++;
  } catch (e) {
    const m = e.message || '';
    if (keyword && !m.includes(keyword)) { console.log(`✗ ${name}\n    报错不含「${keyword}」: ${m}`); fail++; return; }
    console.log(`✓ ${name}  →  ${m}`);
    pass++;
  }
}

